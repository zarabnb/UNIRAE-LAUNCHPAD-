#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp)"
trap 'rm -f "$TMP" "$TMP.out"' EXIT
if node "$ROOT/scripts/production-preflight.mjs" "$TMP" >"$TMP.out" 2>&1; then
  echo "preflight unexpectedly accepted an empty configuration" >&2; exit 1
fi
grep -q 'DATABASE_URL' "$TMP.out"
grep -q 'FACTORY_ETHEREUM_MAINNET' "$TMP.out"
cat > "$TMP" <<'ENV'
DATABASE_URL=postgresql://u:p@db.example:5432/unirae?sslmode=require
CORS_ORIGINS=https://unirae.example
RPC_ETHEREUM_MAINNET=https://rpc.example
FACTORY_ETHEREUM_MAINNET=0x5555555555555555555555555555555555555555
NATIVE_USD_FEED_ETHEREUM_MAINNET=0x2222222222222222222222222222222222222222
WRAPPED_NATIVE_ETHEREUM_MAINNET=0x3333333333333333333333333333333333333333
FEE_VAULT_ETHEREUM_MAINNET=0x4444444444444444444444444444444444444444
FEE_VAULT_START_BLOCK_ETHEREUM_MAINNET=1
RPC_BNB_MAINNET=https://rpc.example
FACTORY_BNB_MAINNET=0x5555555555555555555555555555555555555555
NATIVE_USD_FEED_BNB_MAINNET=0x2222222222222222222222222222222222222222
WRAPPED_NATIVE_BNB_MAINNET=0x3333333333333333333333333333333333333333
FEE_VAULT_BNB_MAINNET=0x4444444444444444444444444444444444444444
FEE_VAULT_START_BLOCK_BNB_MAINNET=1
RPC_ROBINHOOD_MAINNET=https://rpc.example
FACTORY_ROBINHOOD_MAINNET=0x5555555555555555555555555555555555555555
NATIVE_USD_FEED_ROBINHOOD_MAINNET=0x2222222222222222222222222222222222222222
WRAPPED_NATIVE_ROBINHOOD_MAINNET=0x3333333333333333333333333333333333333333
FEE_VAULT_ROBINHOOD_MAINNET=0x4444444444444444444444444444444444444444
FEE_VAULT_START_BLOCK_ROBINHOOD_MAINNET=1
RPC_XLAYER_MAINNET=https://rpc.example
FACTORY_XLAYER_MAINNET=0x5555555555555555555555555555555555555555
NATIVE_USD_FEED_XLAYER_MAINNET=0x2222222222222222222222222222222222222222
WRAPPED_NATIVE_XLAYER_MAINNET=0x3333333333333333333333333333333333333333
FEE_VAULT_XLAYER_MAINNET=0x4444444444444444444444444444444444444444
FEE_VAULT_START_BLOCK_XLAYER_MAINNET=1
ENV
node "$ROOT/scripts/production-preflight.mjs" "$TMP" >/dev/null
echo 'Production preflight rejects incomplete config and accepts a complete four-network shape.'
